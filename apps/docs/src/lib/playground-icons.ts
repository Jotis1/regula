export const PLAYGROUND_ICON_NAMES: string[] = Object.keys(PLAYGROUND_ICONS);

/**
 * Las props con los nombres de icono (`"Plus"`) pasan a los componentes de icono, también dentro de objetos y listas
 * (`{ icon: "Plus" }`). Las props del ejemplo cruzan de Astro como JSON; aquí, ya en el cliente, se resuelven.
 */
export function resolveIcons<T>(value: T, key?: string): T {
	if (typeof value === "string")
		return (key && ICON_KEY.test(key) && PLAYGROUND_ICONS[value] ? PLAYGROUND_ICONS[value] : value) as T;
	if (Array.isArray(value)) return value.map((v) => resolveIcons(v, key)) as T;
	if (
		value &&
		typeof value === "object" &&
		!isValidElement(value) &&
		Object.getPrototypeOf(value) === Object.prototype
	)
		return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolveIcons(v, k)])) as T;
	return value;
}
